function listRegularFiles(root,current=root){
 const files=[];
 for(const name of readdirSync(current).sort(compare)){
  if(current===root&&name==='manifest.json')continue;
  const path=join(current,name),entry=lstatSync(path);
  if(entry.isSymbolicLink())throw Error('OFFLINE_BUNDLE_SYMLINK_REJECTED');
  if(entry.isDirectory())files.push(...listRegularFiles(root,path));
  else if(entry.isFile())files.push(path);
  else throw Error('OFFLINE_BUNDLE_NON_REGULAR_ENTRY');
 }
 return files;
}

export function writeMethodSelfScanArtifacts(output,scan,receipt){
 const methodsColumns=['method_id','method_name','family','mechanism','required_input','falsifier','implementation_state','primary_source_id','provenance_state','dimensions','taxonomy_tags','incoming_relation_count','outgoing_relation_count','survival_status'];
 const methodsRows=scan.methods.map(row=>({...row,survival_status:row.self_contract.survival.overall}));
 const pairColumns=['pair_key','method_id_a','method_id_b','comparison_kind','a_to_b','b_to_a','same_primary_source_id','same_exact_source_locator','same_family','shared_dimensions','shared_trigger_profiles','shared_crosswalk_parents','same_dimension_set','shared_taxonomy_tags','same_taxonomy_signature','same_classifier_question','exact_stored_field_matches','core_static_link_status','metadata_overlap_status','source_lineage_status','independence_status','equivalence_status','corroboration'];
 const pairRows=scan.pair_scan.rows.map(row=>({
  ...row,...row.evidence_vector,...row.assessment,a_to_b:row.declared_relations.a_to_b,b_to_a:row.declared_relations.b_to_a
 }));
 const sourceColumns=['source_id','title','native_url','source_class','review_state','checked_on'];
 const relationColumns=['method_id','related_method_id','relation_type','rationale','evidence_independent','link_status'];
 const implementedColumns=['method_id','canonical_name','implementation_state','required_inputs','complement_methods','inverse','output_type','input_schema_sha256','capsule_sha256','contract_status'];
 const summary={version:scan.version,status:scan.status,inventory:scan.inventory,fingerprints:scan.fingerprints,
  pair_aggregates:scan.pair_scan.aggregates,relation_graph:{isolated_methods:scan.relation_graph.isolated_methods,
   undirected_component_count:scan.relation_graph.undirected_component_count,nontrivial_directed_cycles:scan.relation_graph.nontrivial_directed_cycles,
   maximum_shortest_directed_path:scan.relation_graph.maximum_shortest_directed_path},hook_coverage:scan.hook_coverage,
  open_dependencies:scan.open_dependencies,source_authentication:false,method_execution_performed:false,
  independent_evidence_proven:false,equivalence_proven:false,canonical_promotion:false};
 put(join(output,'scan.json'),JSON.stringify(scan,null,2)+'\n');
 put(join(output,'summary.json'),JSON.stringify(summary,null,2)+'\n');
 put(join(output,'methods.csv'),csv(methodsColumns,methodsRows));
 put(join(output,'pairs.csv'),csv(pairColumns,pairRows));
 put(join(output,'sources.csv'),csv(sourceColumns,scan.sources));
 put(join(output,'relations.csv'),csv(relationColumns,scan.relation_graph.edges));
 put(join(output,'implemented-methods.csv'),csv(implementedColumns,scan.implemented_contracts));
 put(join(output,'MPC-Method-Lab.html'),renderMethodSelfScanUi(scan));
 put(join(output,'MPC-Method-Self-Scan.cmd'),'@echo off\r\nsetlocal EnableExtensions DisableDelayedExpansion\r\nset "MPC_APP=%~dp0MPC-Method-Lab.html"\r\nif not exist "%MPC_APP%" (\r\n echo ERROR: MPC-Method-Lab.html is missing.\r\n echo Press any key to close this window . . .\r\n pause ^>nul\r\n exit /b 1\r\n)\r\nstart "" "%MPC_APP%"\r\nif errorlevel 1 (\r\n echo ERROR: The default browser could not open MPC Method Lab.\r\n echo Press any key to close this window . . .\r\n pause ^>nul\r\n exit /b 1\r\n)\r\nendlocal\r\n');
 put(join(output,'REPORT.md'),report(scan,receipt));
 put(join(output,'receipt.json'),JSON.stringify(receipt,null,2)+'\n');
 const artifacts=listRegularFiles(output).map(path=>{
  const raw=readFileSync(path);
  return {path:relative(output,path).split(sep).join('/'),bytes:raw.length,sha256:sha256(raw)};
 }).sort((a,b)=>compare(a.path,b.path));
 const manifest={format_version:'MPC_METHOD_SELF_SCAN_OFFLINE_MANIFEST_1.0',algorithm:'SHA-256',artifacts,
  artifact_count:artifacts.length,formula_cells_escaped:true,manifest_self_hash_excluded:true,
  source_authentication:false,method_execution_performed:false,canonical_promotion:false};
 put(join(output,'manifest.json'),JSON.stringify(manifest,null,2)+'\n');
 return manifest;
}

// Add a queryable projection to a newly created bundle database. These tables
// are deliberately outside the atlas_* namespace so seed-parity admission
// continues to describe only the checked-in source-derived Atlas.
export function writeMethodSelfScanDatabase(db,scan){
 if(!db||typeof db.exec!=='function'||typeof db.prepare!=='function')throw Error('OFFLINE_SCAN_SQLITE_DATABASE_REQUIRED');
 db.exec('BEGIN IMMEDIATE');
 try{
  db.exec(`CREATE TABLE offline_scan_metadata(key TEXT PRIMARY KEY NOT NULL,value_json TEXT NOT NULL);
   CREATE TABLE offline_scan_implemented(method_id TEXT PRIMARY KEY NOT NULL,canonical_name TEXT NOT NULL,contract_status TEXT NOT NULL,capsule_json TEXT NOT NULL);
   CREATE TABLE offline_scan_methods(method_id TEXT PRIMARY KEY NOT NULL REFERENCES atlas_methods(method_id),method_name TEXT NOT NULL,primary_source_id TEXT NOT NULL,self_contract_json TEXT NOT NULL,dimensions_json TEXT NOT NULL,taxonomy_tags_json TEXT NOT NULL,incoming_relations INTEGER NOT NULL,outgoing_relations INTEGER NOT NULL);
   CREATE TABLE offline_scan_pairs(pair_key TEXT PRIMARY KEY NOT NULL,method_id_a TEXT NOT NULL REFERENCES atlas_methods(method_id),method_id_b TEXT NOT NULL REFERENCES atlas_methods(method_id),comparison_kind TEXT NOT NULL,a_to_b_json TEXT NOT NULL,b_to_a_json TEXT NOT NULL,evidence_vector_json TEXT NOT NULL,assessment_json TEXT NOT NULL);
   CREATE INDEX offline_scan_pairs_a ON offline_scan_pairs(method_id_a,method_id_b);
   CREATE INDEX offline_scan_pairs_b ON offline_scan_pairs(method_id_b,method_id_a);`);
  const metadata=db.prepare('INSERT INTO offline_scan_metadata(key,value_json) VALUES(?,?)');
  for(const [key,value] of Object.entries({version:scan.version,status:scan.status,fingerprints:scan.fingerprints,inventory:scan.inventory,
   pair_aggregates:scan.pair_scan.aggregates,relation_graph:{zero_incoming_count:scan.relation_graph.zero_incoming_count,
    zero_outgoing_count:scan.relation_graph.zero_outgoing_count,isolated_methods:scan.relation_graph.isolated_methods,
    undirected_component_count:scan.relation_graph.undirected_component_count,nontrivial_directed_cycles:scan.relation_graph.nontrivial_directed_cycles,
    maximum_shortest_directed_path:scan.relation_graph.maximum_shortest_directed_path},hook_coverage:scan.hook_coverage,
   dynamic_evaluations:scan.dynamic_evaluations,open_dependencies:scan.open_dependencies,boundaries:{source_authentication:false,
    method_execution_performed:false,independent_evidence_proven:false,equivalence_proven:false,canonical_promotion:false}}))metadata.run(key,JSON.stringify(value));
  const implemented=db.prepare('INSERT INTO offline_scan_implemented(method_id,canonical_name,contract_status,capsule_json) VALUES(?,?,?,?)');
  for(const row of scan.implemented_contracts)implemented.run(row.method_id,row.canonical_name,row.contract_status,JSON.stringify(row));
  const method=db.prepare('INSERT INTO offline_scan_methods(method_id,method_name,primary_source_id,self_contract_json,dimensions_json,taxonomy_tags_json,incoming_relations,outgoing_relations) VALUES(?,?,?,?,?,?,?,?)');
  for(const row of scan.methods)method.run(row.method_id,row.method_name,row.primary_source_id,JSON.stringify(row.self_contract),JSON.stringify(row.dimensions),JSON.stringify(row.taxonomy_tags),row.incoming_relation_count,row.outgoing_relation_count);
  const pair=db.prepare('INSERT INTO offline_scan_pairs(pair_key,method_id_a,method_id_b,comparison_kind,a_to_b_json,b_to_a_json,evidence_vector_json,assessment_json) VALUES(?,?,?,?,?,?,?,?)');
  for(const row of scan.pair_scan.rows)pair.run(row.pair_key,row.method_id_a,row.method_id_b,row.comparison_kind,JSON.stringify(row.declared_relations.a_to_b),JSON.stringify(row.declared_relations.b_to_a),JSON.stringify(row.evidence_vector),JSON.stringify(row.assessment));
  db.exec('COMMIT');
 }catch(error){try{db.exec('ROLLBACK')}catch{}throw error}
 return {status:'OFFLINE_SCAN_SQLITE_PROJECTION_WRITTEN',implemented_rows:scan.implemented_contracts.length,
  method_rows:scan.methods.length,pair_rows:scan.pair_scan.rows.length,canonical_records_modified:false};
}
