const compare=(a,b)=>a<b?-1:a>b?1:0;
const sha256=raw=>createHash('sha256').update(raw).digest('hex');
const csvCell=value=>{
 let text=Array.isArray(value)||value&&typeof value==='object'?JSON.stringify(value):String(value??'');
 if(/^[\s]*[=+@-]/u.test(text))text="'"+text;
 return '"'+text.replaceAll('"','""')+'"';
};
const csv=(columns,rows)=>[columns.map(csvCell).join(','),...rows.map(row=>columns.map(column=>csvCell(row[column])).join(','))].join('\r\n')+'\r\n';
const put=(path,value)=>writeFileSync(path,value,{encoding:'utf8',flag:'wx'});

