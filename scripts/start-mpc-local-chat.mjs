#!/usr/bin/env node
import {mkdir, open, readFile, unlink, lstat} from 'node:fs/promises';
import {join, resolve} from 'node:path';
import {homedir} from 'node:os';
import {spawn} from 'node:child_process';
import {randomUUID} from 'node:crypto';
import {setTimeout as delay} from 'node:timers/promises';

const [major, minor] = process.versions.node.split('.').map(Number);
if (major < 22 || (major === 22 && minor < 13)) {
  console.error('MPC local chat needs Node.js 22.13 or newer. Install the current Node.js LTS from https://nodejs.org/en/download, then reopen this launcher.');
  process.exit(1);
}

const options = {open: true, port: 0};
for (let i = 2; i < process.argv.length; i++) {
  const arg = process.argv[i];
  if (arg === '--no-open') options.open = false;
  else if (arg === '--port') {
    const value = process.argv[++i];
    if (!/^\d+$/u.test(value || '') || Number(value) > 65535) throw new Error('--port needs a number from 0 to 65535.');
    options.port = Number(value);
  } else if (arg === '--data-dir') {
    const value = process.argv[++i];
    if (!value || value.startsWith('--')) throw new Error('--data-dir needs a local directory path.');
    options.dataDir = resolve(value);
  } else if (arg === '--help') {
    console.log('MPC local chat\n  node scripts/start-mpc-local-chat.mjs [--no-open] [--port 0] [--data-dir PATH]\nNo package install is required. Ollama must be installed separately.');
    process.exit(0);
  } else throw new Error('Unknown launcher option: ' + arg);
}

function defaultDataDirectory() {
  if (process.platform === 'win32') return join(process.env.LOCALAPPDATA || join(homedir(), 'AppData', 'Local'), 'MPCWorkspace');
  if (process.platform === 'darwin') return join(homedir(), 'Library', 'Application Support', 'MPCWorkspace');
  return join(process.env.XDG_DATA_HOME || join(homedir(), '.local', 'share'), 'MPCWorkspace');
}
function openBrowser(url) {
  // The URL is generated by this process or matched to its own live instance.
  const target = new URL(url);
  if (target.protocol !== 'http:' || target.hostname !== '127.0.0.1' || target.pathname !== '/' || target.search || target.hash || target.username || target.password) throw new Error('Invalid local workspace URL.');
  let command, args;
  if (process.platform === 'win32') {command = 'cmd.exe'; args = ['/d', '/c', 'start', '""', target.origin];}
  else if (process.platform === 'darwin') {command = 'open'; args = [target.origin];}
  else {command = 'xdg-open'; args = [target.origin];}
  const child = spawn(command, args, {shell: false, detached: true, stdio: 'ignore', windowsHide: true});
  child.on('error', () => console.log('Open this address in your browser: ' + target.origin));
  child.unref();
}
function processAlive(pid) {
  if (!Number.isSafeInteger(pid) || pid < 1) return false;
  try {process.kill(pid, 0); return true;} catch (error) {return error.code === 'EPERM';}
}

const dataDirectory = options.dataDir || defaultDataDirectory();
await mkdir(dataDirectory, {recursive: true, mode: 0o700});
const lockPath = join(dataDirectory, 'local-chat-instance.json');
const owner = randomUUID();
let lock, app, closing = false;
async function ownLockRecord() {
  const stat = await lstat(lockPath);
  if (!stat.isFile() || stat.isSymbolicLink() || stat.nlink !== 1 || stat.size > 4096) throw new Error('The existing local chat instance file is not an ordinary small file. Choose a different --data-dir or inspect it manually.');
  const record = JSON.parse(await readFile(lockPath, 'utf8'));
  if (record.kind !== 'MPC_LOCAL_CHAT_INSTANCE' || record.version !== 1 || typeof record.owner !== 'string' || !Number.isSafeInteger(record.pid)) throw new Error('The existing instance file has an unknown identity. It has been left unchanged.');
  return record;
}
async function acquireLock() {
  for (let attempt = 0; attempt < 2; attempt++) {
    try {
      lock = await open(lockPath, 'wx', 0o600);
      await lock.writeFile(JSON.stringify({kind: 'MPC_LOCAL_CHAT_INSTANCE', version: 1, owner, pid: process.pid, state: 'STARTING'}) + '\n');
      await lock.sync(); return true;
    } catch (error) {
      if (error.code !== 'EEXIST') throw error;
      let existing;
      // A second double-click can arrive before the first process writes its lock.
      for (let retry = 0; retry < 5; retry++) {
        try {existing = await ownLockRecord(); break;} catch (readError) {if (retry === 4) throw readError; await delay(100);}
      }
      if (processAlive(existing.pid)) {
        if (typeof existing.url === 'string' && typeof existing.instance_id === 'string') {
          const parsed = new URL(existing.url);
          if (parsed.protocol === 'http:' && parsed.hostname === '127.0.0.1' && parsed.pathname === '/' && !parsed.search && !parsed.hash && !parsed.username && !parsed.password) {
            let observed;
            try {
              const response = await fetch(parsed.origin + '/api/local/status', {redirect: 'error', signal: AbortSignal.timeout(12_000)});
              if (response.ok) observed = await response.json();
            } catch {}
            if (observed?.app?.instance_id === existing.instance_id) {
              console.log('MPC local chat is already running: ' + parsed.origin);
              if (options.open) openBrowser(parsed.origin); return false;
            }
          }
        }
        throw new Error('MPC local chat is already starting or running for this data directory. Return to its existing window. Its instance file has been preserved.');
      }
      // Recheck identity immediately before removing only a stale lock we recognize.
      const latest = await ownLockRecord();
      if (latest.owner !== existing.owner || processAlive(latest.pid)) throw new Error('Another MPC instance started. Return to its window.');
      await unlink(lockPath);
    }
  }
  throw new Error('Could not acquire the local chat instance lock.');
}
async function close() {
  if (closing) return; closing = true;
  try {if (app) await app.close();}
  finally {
    if (lock) {
      try {await lock.close();} catch {}
      try {if ((await ownLockRecord()).owner === owner) await unlink(lockPath);} catch {}
    }
  }
}

try {
  const acquired = await acquireLock();
  if (!acquired) process.exit(0);
  const {createLocalChatServer} = await import('../lib/local-chat-server.mjs');
  app = createLocalChatServer({dataFile: join(dataDirectory, 'mpc-local-chat.sqlite')});
  const address = await app.listen({port: options.port});
  await lock.truncate(0);
  await lock.write(JSON.stringify({kind: 'MPC_LOCAL_CHAT_INSTANCE', version: 1, owner, pid: process.pid, state: 'RUNNING', ...address}) + '\n', 0, 'utf8');
  await lock.sync();
  console.log('\nMPC Workspace — Local chat\n' + address.url + '\n\nData: ' + dataDirectory + '\nKeep this window open. Press Ctrl+C to stop the local chat service.\nOllama setup and model selection are in the chat screen.\n');
  process.once('SIGINT', () => {close().then(() => process.exit(0));});
  process.once('SIGTERM', () => {close().then(() => process.exit(0));});
  if (options.open) openBrowser(address.url);
} catch (error) {
  console.error('MPC local chat could not start: ' + error.message);
  await close(); process.exitCode = 1;
}
